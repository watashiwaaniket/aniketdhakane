import fs from "fs";
import path from "path";
import matter from "gray-matter";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const blogDir = path.join(root, "content/blog");
const outFile = path.join(root, "src/lib/blog/generated-articles.ts");

function slugFromFilename(filename) {
  return filename.replace(/\.md$/, "");
}

function asText(value, fallback = "") {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  if (value === null || value === undefined || value === "") return fallback;
  return String(value);
}

function buildPreview(content) {
  const plain = content
    .replace(/^#+\s+/gm, "")
    .replace(/[*_`>#-]/g, "")
    .replace(/\s+/g, " ")
    .trim();

  return plain.length > 160 ? `${plain.slice(0, 160)}…` : plain;
}

function parseArticle(filename) {
  const slug = slugFromFilename(filename);
  const raw = fs.readFileSync(path.join(blogDir, filename), "utf8");
  const { data, content } = matter(raw);
  const title = asText(data.title, slug);
  const body = content.trim();

  const article = {
    slug: asText(data.slug, slug),
    title,
    nav: asText(data.nav, title),
    date: asText(data.date, new Date().toISOString().slice(0, 10)),
    author: asText(data.author, "Aniket Dhakane"),
    preview: asText(data.preview, buildPreview(body)),
    content: body,
  };
  const askPrompt = asText(data.askPrompt);
  if (askPrompt) {
    article.askPrompt = askPrompt;
    article.askLabel = asText(
      data.askLabel,
      "Want to dive much deeper? Ask your favorite AI.",
    );
  }
  return article;
}

const articles = fs.existsSync(blogDir)
  ? fs
      .readdirSync(blogDir)
      .filter((file) => file.endsWith(".md"))
      .map(parseArticle)
      .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
  : [];

const fileContents = `// This file is auto-generated by scripts/generate-blog.mjs
// Do not edit by hand. Edit content/blog/*.md and re-run generate.
import type { Article } from "./article-types";

export const articles: Article[] = ${JSON.stringify(articles, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, fileContents);
console.log(
  `Generated ${articles.length} article(s) -> src/lib/blog/generated-articles.ts`,
);
