import fs from "fs";
import path from "path";
import matter from "gray-matter";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const projectsDir = path.join(root, "content/projects");
const outFile = path.join(root, "src/lib/projects/generated-projects.ts");

function slugFromFilename(filename) {
  return filename.replace(/\.md$/, "");
}

function buildPreview(content) {
  const plain = content
    .replace(/^#+\s+/gm, "")
    .replace(/[*_`>#-]/g, "")
    .replace(/\s+/g, " ")
    .trim();

  return plain.length > 120 ? `${plain.slice(0, 120)}…` : plain;
}

function normalizeStack(value) {
  if (Array.isArray(value)) {
    return value.map(String).filter(Boolean);
  }
  if (typeof value === "string" && value.trim()) {
    return value
      .split(",")
      .map((part) => part.trim())
      .filter(Boolean);
  }
  return [];
}

function parseProjectFile(filename) {
  const slug = slugFromFilename(filename);
  const raw = fs.readFileSync(path.join(projectsDir, filename), "utf8");
  const { data, content } = matter(raw);

  return {
    slug: data.slug ?? slug,
    title: data.title ?? slug,
    date: data.date ?? new Date().toISOString().slice(0, 10),
    category: data.category ?? "Other",
    status: data.status ?? "Shipped",
    link: data.link ?? null,
    stack: normalizeStack(data.stack),
    preview: data.preview ?? buildPreview(content),
    content: content.trim(),
  };
}

const projects = fs.existsSync(projectsDir)
  ? fs
      .readdirSync(projectsDir)
      .filter((file) => file.endsWith(".md"))
      .map(parseProjectFile)
      .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
  : [];

const fileContents = `// This file is auto-generated by scripts/generate-projects.mjs
// Do not edit by hand — edit content/projects/*.md and re-run generate.
import type { Project } from "./project-types";

export const projects: Project[] = ${JSON.stringify(projects, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, fileContents);
console.log(
  `Generated ${projects.length} project note(s) -> src/lib/projects/generated-projects.ts`,
);
